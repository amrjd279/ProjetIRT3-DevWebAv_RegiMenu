-- Script d'initialisation de la base de données (H2 et PostgreSQL)
-- Strictement requis par le cahier des charges (Section 4.1 & 4.3 : Spring JdbcClient, pas de JPA)

CREATE TABLE IF NOT EXISTS user_profiles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(255) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    is_vegetarian BOOLEAN DEFAULT FALSE,
    is_vegan BOOLEAN DEFAULT FALSE,
    is_gluten_free BOOLEAN DEFAULT FALSE,
    is_lactose_free BOOLEAN DEFAULT FALSE,
    request_count INT DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS daily_menus (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_profile_id BIGINT,
    menu_date DATE NOT NULL,
    generated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS daily_meals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    daily_menu_id BIGINT NOT NULL,
    external_recipe_id BIGINT NOT NULL,
    title VARCHAR(500) NOT NULL,
    image_url VARCHAR(1000),
    ready_in_minutes INT,
    is_vegetarian BOOLEAN DEFAULT FALSE,
    is_vegan BOOLEAN DEFAULT FALSE,
    CONSTRAINT fk_daily_meal_menu FOREIGN KEY (daily_menu_id) REFERENCES daily_menus(id) ON DELETE CASCADE
);
